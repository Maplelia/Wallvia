// scripts/build-options.mjs — the one description of how `main.js` is built.
//
// Both `esbuild.config.mjs` (the dev/prod build) and
// `scripts/verify-artifact.mjs` (the artifact↔source consistency guard) import
// this, because two option objects that drift apart would silently defeat the
// guard: the rebuild would differ for a reason that has nothing to do with the
// sources.
import path from "node:path";
import { fileURLToPath } from "node:url";
import { builtinModules } from "node:module";

/** Repository root, independent of the caller's working directory. */
export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Prepended to the bundle so a stray `main.js` is identifiable. */
export const BANNER = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/**
 * esbuild options for the Obsidian bundle.
 *
 * `outfile` is resolved against the repository root so the same options work
 * from a verifier that builds into a temp directory.
 */
export function buildOptions({ prod = false, outfile = "main.js" } = {}) {
  return {
    banner: { js: BANNER },
    entryPoints: [path.join(REPO_ROOT, "obsidian/main.ts")],
    bundle: true,
    external: [
      "obsidian",
      "electron",
      "@codemirror/autocomplete",
      "@codemirror/collab",
      "@codemirror/commands",
      "@codemirror/language",
      "@codemirror/lint",
      "@codemirror/search",
      "@codemirror/state",
      "@codemirror/view",
      "@lezer/common",
      "@lezer/highlight",
      "@lezer/lr",
      ...builtinModules,
    ],
    format: "cjs",
    target: "es2021",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: path.isAbsolute(outfile) ? outfile : path.join(REPO_ROOT, outfile),
    minify: prod,
  };
}
